import test from 'node:test';
import assert from 'node:assert/strict';
import * as THREE from 'three';
import { Window } from 'happy-dom';
import { World } from '../src/world.js';
import { ModelCache } from '../src/model-cache.js';
import { createTrack } from '../src/game/track.js';
import { Race } from '../src/game/race.js';
import { chaseFraming, chaseEye } from '../src/viewport.js';

test('strategy bands, kart feedback and cosmetic changes share bounded resources and dispose on scene changes', async t => {
  const window = new Window({ url: 'http://localhost/' }), document = window.document, originals = new Map();
  for (const [key, value] of Object.entries({ window, document, navigator: window.navigator, innerWidth: 844, innerHeight: 390, requestAnimationFrame: () => 1, cancelAnimationFrame() {} })) {
    originals.set(key, Object.getOwnPropertyDescriptor(globalThis, key));Object.defineProperty(globalThis, key, { configurable: true, writable: true, value });
  }
  window.HTMLCanvasElement.prototype.getContext = () => ({ fillRect() {}, fillText() {} });
  const canvas = document.createElement('canvas');canvas.getBoundingClientRect = () => ({ width: 844, height: 390 });
  const renderer = { domElement: canvas, shadowMap: {}, setPixelRatio() {}, setSize() {}, render() {}, renderLists: { dispose() {} }, dispose() {} };
  const track = createTrack('candy-hills'), race = new Race(track), cache = new ModelCache(() => new Promise(() => {}));
  const world = new World(canvas, track, { createRenderer: () => renderer, modelCache: cache });
  t.after(() => { world.dispose();for (const [key, descriptor] of originals) { if (descriptor) Object.defineProperty(globalThis, key, descriptor);else delete globalThis[key]; }window.close(); });
  await world.createKarts({ progressive: true });world.setLineup(race.racers);
  assert.equal(world.strategyRibbons.length, 12, 'three short recharge bands plus one long sprint band per section');
  const player = race.player, kart = world.karts[0];player.shield = 5;player.itemProtection = 1;player.draftCharge = .5;
  world.setCosmetics({ paint: '#65cfb0', trail: '#ffcf68', title:'晴空杯车手' });world.update(1 / 60, race);
  assert.equal(kart.paint.color.getHexString(), '65cfb0');assert.equal(kart.effects.shield.visible, true);assert.equal(kart.effects.protection.visible, true);assert.equal(kart.effects.draft.visible, true);
  assert.equal(kart.effects.sticker.visible,true);assert.equal(world.karts[1].effects.sticker.visible,false);
  const geometry = kart.effects.draft.geometry, count = world.scene.children.length;
  for (let i = 0; i < 50; i++) world.update(1 / 60, race);
  assert.equal(kart.effects.draft.geometry, geometry);assert.equal(world.scene.children.length, count, 'feedback must not allocate scene objects every frame');
  player.distance += 2;player.offset = 3;world.update(1 / 60, race);
  const pose = track.sample(player.distance);
  assert.ok(Math.abs(kart.root.position.x - (pose.x + pose.nx * player.offset)) < 1e-8, 'our own predicted car responds without an extra visual interpolation delay');
  assert.ok(Math.abs(kart.root.position.z - (pose.z + pose.nz * player.offset)) < 1e-8);
  const spectator=race.racers[1];spectator.distance=300;
  race.cameraPlayer=spectator;world.update(1/60,race);
  const eye=chaseEye(track,spectator.distance,spectator.offset,chaseFraming(world.viewport,spectator.speed));
  assert.ok(world.camera.position.distanceTo(new THREE.Vector3(eye.x,eye.y,eye.z))<1e-8,'switching spectator targets resets the chase camera immediately');
  assert.equal(world.localPlayerId,player.id);assert.equal(kart.paint.color.getHexString(),'65cfb0');
  assert.equal(world.karts[1].paint.color.getHexString(),new THREE.Color(spectator.color).getHexString(),'spectating never transfers our paint to another driver');
  world.setCosmetics({ paint: null, trail: null });assert.equal(kart.paint.color.getHexString(), new THREE.Color(player.color).getHexString());
  player.shield = 0;player.itemProtection = 0;player.draftCharge = 0;player.draftBoost = 0;world.update(1 / 60, race);
  assert.equal(kart.effects.shield.visible, false);assert.equal(kart.effects.protection.visible, false);assert.equal(kart.effects.draft.visible, false);
  assert.equal(kart.effects.sticker.visible,false,'unequipping the title removes its cosmetic sticker');
  world.setGraphicsQuality('smooth');world.clearParticles();
  for(let i=0;i<100;i++)world.particle(new THREE.Vector3(),0xffffff,new THREE.Vector3(),1);
  assert.equal(world.particles.length,32,'smooth quality bounds feedback costs while leaving effects visible');
  let sharedDisposals=0;world.materials.white.addEventListener('dispose',()=>sharedDisposals++);
  world.updateGhost({distance:100,offset:0,character:'fox'});
  assert.equal(sharedDisposals,0,'creating a ghost retains scene materials');
  const ghostMaterials=new Set();world.ghost.traverse(object=>{if(object.material)ghostMaterials.add(object.material);});
  assert.ok(ghostMaterials.size<10,'ghost meshes reuse cloned materials');
  let ghostDisposals=0;for(const material of ghostMaterials)material.addEventListener('dispose',()=>ghostDisposals++);
  world.updateGhost({distance:100,offset:0,character:'rabbit'});
  assert.equal(ghostDisposals,ghostMaterials.size,'changing the ghost character releases its previous materials');
  assert.equal(sharedDisposals,0);
  let disposed = 0;const seen = new Set();world.scene.traverse(object => { if (object.geometry && !seen.has(object.geometry)) { seen.add(object.geometry);object.geometry.addEventListener('dispose', () => disposed++); } });
  world.dispose();assert.equal(disposed, seen.size);assert.equal(sharedDisposals,1);
});
